// 13. 10. 2026; the Benešov cash and carry by the station). Prices in CZK
// including VAT, per keg, as the list prints them ("PC-A s DPH"); `inStock`
// is its "Skladem" column on that day. Only 15, 20, 30 and 50 l kegs
// ("SUD" and "POLYKEG" rows); the one 10 l keg is left out. The list has no
// product codes, so `code` is ours (name and size), stable for stored items;
// the order summary quotes name and size, which is what the shop needs.
// Names are tidied from the list's capitals ("12% PILSNER URQUELL 30L SUD"
// becomes "Pilsner Urquell 12°"); the size lives in `liters`.
//
// A static copy on purpose: the shop has no API and publishes the list as a
// PDF (https://www.benecentrum.cz/cenik.pdf, BEER_SHOP.priceListUrl). Refresh
// by hand when they print a new one (and bump the date below).

